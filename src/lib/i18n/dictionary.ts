/**
 * Appended to the interviewer's system instruction so the interview itself
 * follows the interface language — not just the buttons around it.
 */
export function interviewInstruction(lang: Lang): string {
  if (lang === "en") return "";
  const name = LANGS[lang].name;
  return (
    ` Conduct this entire interview in ${name}.` +
    ` Every question, every follow-up and all written or spoken feedback must be in ${name},` +
    " regardless of the language of the job description or the candidate's answers." +
    " Keep widely used English technical terms and product names (for example SQL, dbt, Snowflake, Airflow) as they are."
  );
}

